<?php
/**
 * SQLite Schema Generator (intent 003, unit 010 / EF-7)
 * CampusConnect - Agile Software Project Management
 *
 * Generates the canonical SQLite DDL from db/schema.sql, translating
 * MySQL-specific syntax (AUTO_INCREMENT, ENGINE/CHARSET, ENUM, TIMESTAMP)
 * into SQLite-compatible DDL.
 *
 * Replaces hand-maintained duplicate SQLite schemas in config/Database.php,
 * ensuring db/schema.sql remains the single source of truth.
 *
 * Usage:
 *   php scripts/generate_sqlite_schema.php [--stdout]
 */

function generateSqliteSchema(?string $mysqlDdl = null): string {
    if ($mysqlDdl === null) {
        $schemaPath = __DIR__ . '/../db/schema.sql';
        if (!file_exists($schemaPath)) {
            throw new RuntimeException("Source schema file not found: {$schemaPath}");
        }
        $mysqlDdl = file_get_contents($schemaPath);
    }

    // Normalise line endings
    $sql = str_replace("\r\n", "\n", $mysqlDdl);

    // Remove comments, CREATE DATABASE, and USE statements
    $lines = explode("\n", $sql);
    $filteredLines = [];
    foreach ($lines as $line) {
        $trimmed = trim($line);
        if (str_starts_with($trimmed, '--') || str_starts_with($trimmed, '/*') || str_starts_with($trimmed, '*')) {
            continue;
        }
        if (preg_match('/^(CREATE\s+DATABASE|USE\s+)/i', $trimmed)) {
            continue;
        }
        $filteredLines[] = $line;
    }
    $cleanSql = implode("\n", $filteredLines);

    // Find each CREATE TABLE statement
    // Match: CREATE TABLE [IF NOT EXISTS] `?(\w+)`?\s*\((.+?)\)\s*(?:ENGINE=.*?)?;
    $tablePattern = '/CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?`?(\w+)`?\s*\((.*?)\)\s*(?:ENGINE[^;]*)?;/si';

    $sqliteTables = [];
    $sqliteIndexes = [];

    if (!preg_match_all($tablePattern, $cleanSql, $matches, PREG_SET_ORDER)) {
        throw new RuntimeException("No CREATE TABLE statements found in input DDL.");
    }

    foreach ($matches as $match) {
        $tableName = $match[1];
        $body = trim($match[2]);

        $columnsAndConstraints = splitTableDefinitions($body);
        $translatedBody = [];

        foreach ($columnsAndConstraints as $def) {
            $defTrim = trim($def);
            if ($defTrim === '') {
                continue;
            }

            // 1. Separate inline INDEX / KEY definitions into standalone CREATE INDEX statements
            if (preg_match('/^(?:INDEX|KEY)\s+`?(\w+)`?\s*\((.+?)\)$/i', $defTrim, $m)) {
                $idxName = $m[1];
                $idxCols = $m[2];
                $sqliteIndexes[] = "CREATE INDEX IF NOT EXISTS {$idxName} ON {$tableName}({$idxCols});";
                continue;
            }

            // 2. UNIQUE KEY uq_name (col1, col2) -> UNIQUE (col1, col2)
            if (preg_match('/^UNIQUE\s+(?:KEY|INDEX)\s*(?:`?\w+`?\s*)?\((.+?)\)$/i', $defTrim, $m)) {
                $translatedBody[] = "    UNIQUE ({$m[1]})";
                continue;
            }

            // 3. Remove CONSTRAINT name from FOREIGN KEY and CHECK for cleaner SQLite syntax
            if (preg_match('/^CONSTRAINT\s+`?\w+`?\s+(FOREIGN\s+KEY.+)$/i', $defTrim, $m)) {
                $defTrim = $m[1];
            } elseif (preg_match('/^CONSTRAINT\s+`?\w+`?\s+(CHECK.+)$/i', $defTrim, $m)) {
                $defTrim = $m[1];
            }

            // 4. Translate column definitions
            $translated = translateColumnOrConstraint($defTrim);
            if ($translated !== '') {
                $translatedBody[] = "    " . $translated;
            }
        }

        $sqliteTables[] = "CREATE TABLE IF NOT EXISTS {$tableName} (\n" . implode(",\n", $translatedBody) . "\n);";
    }

    $out = "-- Auto-generated SQLite schema from db/schema.sql (intent 003, unit 010 / EF-7)\n";
    $out .= "-- Single source of truth: do not edit this file by hand. Regenerate via:\n";
    $out .= "--   php scripts/generate_sqlite_schema.php\n\n";
    $out .= implode("\n\n", $sqliteTables) . "\n\n";
    if (!empty($sqliteIndexes)) {
        $out .= implode("\n", $sqliteIndexes) . "\n";
    }

    return $out;
}

/**
 * Split the comma-delimited table items while respecting nested parentheses
 * (such as in ENUM('a','b'), CHECK (col IN (...)), or DECIMAL(10,2)).
 */
function splitTableDefinitions(string $body): array {
    $items = [];
    $current = '';
    $depth = 0;
    $length = strlen($body);

    for ($i = 0; $i < $length; $i++) {
        $char = $body[$i];
        if ($char === '(') {
            $depth++;
        } elseif ($char === ')') {
            $depth--;
        }

        if ($char === ',' && $depth === 0) {
            $items[] = trim($current);
            $current = '';
        } else {
            $current .= $char;
        }
    }

    if (trim($current) !== '') {
        $items[] = trim($current);
    }

    return $items;
}

/**
 * Translate a single column definition or table constraint to SQLite dialect.
 */
function translateColumnOrConstraint(string $def): string {
    // Normalise internal whitespace and newlines first
    $d = preg_replace('/\s+/', ' ', trim($def));

    // Remove CONSTRAINT name from FOREIGN KEY and CHECK for cleaner SQLite syntax
    if (preg_match('/^CONSTRAINT\s+`?\w+`?\s+(FOREIGN\s+KEY.+)$/i', $d, $m)) {
        $d = $m[1];
    } elseif (preg_match('/^CONSTRAINT\s+`?\w+`?\s+(CHECK.+)$/i', $d, $m)) {
        $d = $m[1];
    }

    // Check if it's already a table constraint (PRIMARY KEY, FOREIGN KEY, CHECK, UNIQUE)
    if (preg_match('/^(?:PRIMARY\s+KEY|FOREIGN\s+KEY|CHECK|UNIQUE)\b/i', $d)) {
        return $d;
    }

    // INT AUTO_INCREMENT PRIMARY KEY -> INTEGER PRIMARY KEY AUTOINCREMENT
    $d = preg_replace('/\bINT(?:\(\d+\))?\s+AUTO_INCREMENT\s+PRIMARY\s+KEY\b/i', 'INTEGER PRIMARY KEY AUTOINCREMENT', $d);

    // VARCHAR(n) -> TEXT
    $d = preg_replace('/\bVARCHAR\(\d+\)/i', 'TEXT', $d);

    // TINYINT(1) / TINYINT -> INTEGER
    $d = preg_replace('/\bTINYINT(?:\(\d+\))?/i', 'INTEGER', $d);

    // INT(n) or INT -> INTEGER
    $d = preg_replace('/\bINT(?:\(\d+\))?\b/i', 'INTEGER', $d);

    // TIMESTAMP [NOT NULL] DEFAULT CURRENT_TIMESTAMP [ON UPDATE CURRENT_TIMESTAMP] -> DATETIME DEFAULT CURRENT_TIMESTAMP
    $d = preg_replace('/TIMESTAMP\s+(?:NOT\s+NULL\s+)?DEFAULT\s+CURRENT_TIMESTAMP\s+ON\s+UPDATE\s+CURRENT_TIMESTAMP/i', 'DATETIME DEFAULT CURRENT_TIMESTAMP', $d);
    $d = preg_replace('/TIMESTAMP\s+NULL\s+DEFAULT\s+NULL/i', 'DATETIME DEFAULT NULL', $d);
    $d = preg_replace('/TIMESTAMP\s+(?:NOT\s+NULL\s+)?DEFAULT\s+CURRENT_TIMESTAMP/i', 'DATETIME DEFAULT CURRENT_TIMESTAMP', $d);

    // ENUM translation:
    // e.g. role ENUM('student', 'society_admin', 'system_admin') DEFAULT 'student'
    // -> role TEXT DEFAULT 'student'
    // e.g. reason ENUM('spam', 'harassment') NOT NULL
    // -> reason TEXT NOT NULL CHECK (reason IN ('spam', 'harassment'))
    // e.g. status ENUM('pending', 'dismissed', 'actioned') NOT NULL DEFAULT 'pending'
    // -> status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'dismissed', 'actioned'))
    if (preg_match('/^`?(\w+)`?\s+ENUM\s*\((.+?)\)(.*)$/i', $d, $m)) {
        $colName = $m[1];
        $enumVals = $m[2];
        $rest = trim($m[3]);

        // For role, keep cleaner backward-compatible column def
        if ($colName === 'role') {
            $d = "{$colName} TEXT {$rest}";
        } else {
            // For reason and status (Unit 008 / EF-5 constraints), generate explicit CHECK constraint
            $d = "{$colName} TEXT {$rest} CHECK ({$colName} IN ({$enumVals}))";
        }
    }

    // Strip character set and collate specifications
    $d = preg_replace('/\s+CHARACTER\s+SET\s+\w+/i', '', $d);
    $d = preg_replace('/\s+COLLATE\s+\w+/i', '', $d);

    // Normalise multiple whitespace
    $d = preg_replace('/\s+/', ' ', $d);

    return trim($d);
}

// CLI Execution entry point
if (php_sapi_name() === 'cli' && isset($argv[0]) && realpath($argv[0]) === realpath(__FILE__)) {
    try {
        $sqliteDdl = generateSqliteSchema();
        $targetPath = __DIR__ . '/../db/schema_sqlite.sql';

        if (in_array('--stdout', $argv, true)) {
            echo $sqliteDdl;
        } else {
            file_put_contents($targetPath, $sqliteDdl);
            echo "Successfully generated SQLite schema at {$targetPath}\n";
        }
    } catch (Throwable $e) {
        fwrite(STDERR, "Error generating SQLite schema: " . $e->getMessage() . "\n");
        exit(1);
    }
}
